#!/bin/bash
# Static analysis of the AmmarServer sources with cppcheck.
#
#   ./tests/run_cppcheck.sh                 # core library + its dependencies + vanilla server
#   ./tests/run_cppcheck.sh src/Services    # any other path(s) instead
#
# The full report is written to build/cppcheck/report.txt, a per-severity and
# per-check count is printed, and errors/warnings are listed on the terminal.
#
# Exit status: 1 when cppcheck reports anything of severity "error" or "warning".

set -u

SCRIPT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
REPO_ROOT="$( cd "$SCRIPT_DIR/.." && pwd )"
OUT_DIR="$REPO_ROOT/build/cppcheck"
REPORT="$OUT_DIR/report.txt"

command -v cppcheck >/dev/null || { echo "cppcheck is not installed" >&2; exit 1; }

cd "$REPO_ROOT" || exit 1
mkdir -p "$OUT_DIR/cache"

if [ $# -gt 0 ]; then
  TARGETS=("$@")
else
  TARGETS=(src/AmmServerlib src/Hashmap src/InputParser src/Services/AmmarServer)
fi

run_cppcheck() {
  cppcheck --enable=warning,style,performance,portability \
           --inconclusive --std=c11 --quiet \
           --inline-suppr \
           --suppress=missingIncludeSystem \
           --suppress='identicalConditionAfterEarlyExit:*/stringscanners/*' \
           -j"$(nproc)" \
           --template='{file}:{line}: {severity}: [{id}] {message}' \
           "$@"
}

# stringscanners/ is generated by StringRecognizer, its repeated length guards are suppressed above.
# uringAPIServer.c selects its implementation with __has_include, which cppcheck cannot evaluate, so the
# file is left out of the main pass and checked on its own with the io_uring implementation forced on.
URING=src/AmmServerlib/threads/uringAPIServer.c
run_cppcheck --force --cppcheck-build-dir="$OUT_DIR/cache" -i "$URING" "${TARGETS[@]}" 2> "$REPORT"
if [ $# -eq 0 ]; then
  run_cppcheck -DURING_API_SUPPORTED=1 "$URING" 2>> "$REPORT"
fi

echo "=== by severity ==="
grep -oE ': (error|warning|style|performance|portability|information): ' "$REPORT" | sort | uniq -c | sort -rn
echo
echo "=== by check ==="
grep -oE '\[[A-Za-z0-9_]+\]' "$REPORT" | sort | uniq -c | sort -rn
echo
echo "=== errors and warnings ==="
grep -E ': (error|warning): ' "$REPORT"
echo
echo "Full report: $REPORT"

! grep -qE ': (error|warning): ' "$REPORT"
