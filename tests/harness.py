class Response:
    def __init__(self, status, reason, headers, body, interim=None):
        self.status = status
        self.reason = reason
        self.headers = headers
        self.body = body
        self.interim = interim or []

    def header(self, name):
        values = self.headers.get(name.lower())
        return values[0] if values else None

    def header_all(self, name):
        return self.headers.get(name.lower(), [])


class RawConnection:
    def __init__(self, port, timeout=5.0):
        self.socket = socket.create_connection(("127.0.0.1", port), timeout=timeout)
        self.socket.settimeout(timeout)
        self.buffer = b""

    def send(self, data):
        self.socket.sendall(data)

    def close(self):
        try:
            self.socket.close()
        except OSError:
            pass

    def _receive_some(self):
        data = self.socket.recv(65536)
        if not data:
            raise ConnectionError("connection closed before a complete response")
        self.buffer += data

    def _read_header_block(self):
        while True:
            crlf = self.buffer.find(b"\r\n\r\n")
            lf = self.buffer.find(b"\n\n")
            if crlf >= 0 and (lf < 0 or crlf <= lf):
                block = self.buffer[:crlf + 4]
                self.buffer = self.buffer[crlf + 4:]
                return block
            if lf >= 0:
                block = self.buffer[:lf + 2]
                self.buffer = self.buffer[lf + 2:]
                return block
            self._receive_some()

    @staticmethod
    def _parse_header_block(block):
        lines = block.split(b"\n")
        status_line = lines[0].rstrip(b"\r").decode("latin-1")
        parts = status_line.split()
        if len(parts) < 2:
            raise ValueError("bad status line: %r" % status_line)
        status = int(parts[1])
        reason = " ".join(parts[2:])

        headers = {}
        for line in lines[1:]:
            line = line.rstrip(b"\r")
            if not line or b":" not in line:
                continue
            name, value = line.split(b":", 1)
            headers.setdefault(name.decode("latin-1").lower(), []).append(value.strip().decode("latin-1"))
        return status, reason, headers

    def read_header(self):
        return self._parse_header_block(self._read_header_block())

    def _read_exact(self, length):
        while len(self.buffer) < length:
            self._receive_some()
        body = self.buffer[:length]
        self.buffer = self.buffer[length:]
        return body

    def _read_until_eof(self):
        old_timeout = self.socket.gettimeout()
        self.socket.settimeout(2.0)
        try:
            while True:
                data = self.socket.recv(65536)
                if not data:
                    break
                self.buffer += data
        except socket.timeout:
            pass
        finally:
            self.socket.settimeout(old_timeout)
        body = self.buffer
        self.buffer = b""
        return body

    def read_response(self, method="GET", skip_interim=True):
        interim = []
        while True:
            status, reason, headers = self.read_header()
            if 100 <= status < 200:
                interim.append((status, headers))
                if skip_interim:
                    continue
                return Response(status, reason, headers, b"", interim)
            break

        body = b""
        if method.upper() != "HEAD" and status not in (204, 304):
            transfer_encoding = (headers.get("transfer-encoding") or [""])[0]
            if "chunked" in transfer_encoding.lower():
                body = self._read_until_eof()  # the server never emits chunked responses
            elif "content-length" in headers:
                body = self._read_exact(int(headers["content-length"][0]))
            else:
                body = self._read_until_eof()

        return Response(status, reason, headers, body, interim)


def make_request(method, target, headers=None, body=b"", version="HTTP/1.1", host="auto", port=0):
    lines = ["%s %s %s" % (method, target, version)]
    if host == "auto":
        lines.append("Host: 127.0.0.1:%d" % port)
    elif host is not None:
        lines.append(host)
    for name, value in headers or []:
        lines.append("%s: %s" % (name, value))
    return ("\r\n".join(lines) + "\r\n\r\n").encode("latin-1") + body


def multipart_body(field="user", value="pentestuser", boundary=MULTIPART_BOUNDARY,
                   extra_part_headers=None):
    part_headers = extra_part_headers or []
    header_block = "".join("%s\r\n" % line for line in part_headers)
    return (
        "--%s\r\n"
        'Content-Disposition: form-data; name="%s"\r\n'
        "%s"
        "\r\n"
        "%s\r\n"
        "--%s--\r\n" % (boundary, field, header_block, value, boundary)
    ).encode("latin-1")


def chunk_encode(data, sizes=None):
    if sizes is None:
        sizes = [len(data)] if data else []
    output = b""
    position = 0
    for size in sizes:
        chunk = data[position:position + size]
        position += size
        if not chunk:
            continue
        output += ("%x\r\n" % len(chunk)).encode("latin-1") + chunk + b"\r\n"
    if position < len(data):
        chunk = data[position:]
        output += ("%x\r\n" % len(chunk)).encode("latin-1") + chunk + b"\r\n"
    return output + b"0\r\n\r\n"


def raw_exchange(port, payload, timeout=3.0):
    """Send raw bytes and read until the peer closes (or the timeout expires)."""
    sock = socket.create_connection(("127.0.0.1", port), timeout=timeout)
    sock.settimeout(timeout)
    try:
        data = b""
        try:
            sock.sendall(payload)
            while True:
                chunk = sock.recv(65536)
                if not chunk:
                    break
                data += chunk
        except (socket.timeout, ConnectionResetError, BrokenPipeError):
            # A server that rejects oversized input may close/reset while the
            # request is still being written. Whatever was received is enough
            # for the status assertions.
            pass
        return data
    finally:
        sock.close()


def parsed_status(raw):
    if not raw:
        return None
    first_line = raw.split(b"\n", 1)[0].rstrip(b"\r")
    parts = first_line.split()
    if len(parts) < 2 or not parts[0].startswith(b"HTTP/"):
        return None
    try:
        return int(parts[1])
    except ValueError:
        return None


class ServerTestCase(unittest.TestCase):
    server_config = None
    server_config_files = None
    explicit_conf = True

    @classmethod
    def setUpClass(cls):
        kwargs = {"explicit_conf": cls.explicit_conf}
        if cls.server_config_files is not None:
            kwargs["config_files"] = cls.server_config_files
        else:
            kwargs["config"] = cls.server_config
        cls.server = Server(**kwargs)
        cls.port = cls.server.port

    @classmethod
    def tearDownClass(cls):
        cls.server.stop()

    def connect(self):
        return RawConnection(self.port)

    def request(self, method, target, headers=None, body=b"", version="HTTP/1.1",
                host="auto", close=True, connection=None):
        own_connection = connection is None
        connection = connection or self.connect()
        request_headers = list(headers or [])
        if close:
            request_headers.append(("Connection", "close"))
        try:
            connection.send(make_request(method, target, request_headers, body, version, host, self.port))
            return connection.read_response(method)
        finally:
            if own_connection:
                connection.close()
