"""Shared harness for the AmmarServer test suite.

Every test class starts the real ``ammarserver`` binary on a free loopback
port with its own temporary web root, templates directory, log directory and
configuration file, then talks to it over raw sockets so header framing can be
asserted exactly.  No third-party Python packages are required.
"""

import os
import shutil
import socket
import subprocess
import tempfile
import time
import unittest

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

SERVER_BINARY = os.environ.get("AMMARSERVER_BINARY") or os.path.join(
    REPO_ROOT, "src", "Services", "AmmarServer", "ammarserver"
)
LIBRARY_DIR = os.environ.get("AMMARSERVER_LIBRARY_DIR") or os.path.join(
    REPO_ROOT, "src", "AmmServerlib"
)

FIXED_MTIME = 1700000000  # Tue, 14 Nov 2023 22:13:20 GMT
RANGE_BYTES = bytes(range(36))
MULTIPART_BOUNDARY = "PentestBoundary42"
PNG_BYTES = b"\x89PNG\r\n\x1a\n" + b"\x00" * 16

DEFAULT_CONFIG = {
    "Timeout": 5,
    "KeepAlive": "On",
    "Caching": "On",
    "EnablePost": "On",
    "MaxPostTransactionSize": 4 * 1024 * 1024,
    "MaxCacheSize": 64,
    "MaxCacheSizeForEachFile": 4,
    "MaxSeperateCacheItems": 256,
}


def free_port():
    sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    sock.bind(("127.0.0.1", 0))
    port = sock.getsockname()[1]
    sock.close()
    return port


def write_config(path, settings):
    with open(path, "w", encoding="utf-8") as config:
        config.write("# generated by the AmmarServer test suite\n")
        for key, value in settings.items():
            config.write("%s\t%s\n" % (key, value))
        config.write("# a comment and a blank line follow\n\n")


class Server:
    """One isolated server instance."""

    def __init__(self, config=None, config_files=None, explicit_conf=True):
        self.temp_dir = tempfile.mkdtemp(prefix="ammarserver-test-")
        self.web_root = os.path.join(self.temp_dir, "www")
        self.templates_root = os.path.join(self.temp_dir, "templates")
        self.log_dir = os.path.join(self.temp_dir, "log")
        os.makedirs(self.web_root)
        os.makedirs(os.path.join(self.web_root, "subdir"))
        os.makedirs(self.templates_root)
        os.makedirs(self.log_dir)

        self._create_fixtures()

        settings = dict(DEFAULT_CONFIG)
        if config:
            settings.update(config)

        self.log_path = os.path.join(self.temp_dir, "server.log")
        self.log_file = open(self.log_path, "wb")

        self.port = free_port()
        command = [
            SERVER_BINARY,
            "-p", str(self.port),
            "-bind", "127.0.0.1",
            "-rootdir", self.web_root,
            "-templatedir", self.templates_root,
        ]

        if config_files is None:
            config_path = os.path.join(self.temp_dir, "ammServ.conf")
            write_config(config_path, settings)
            if explicit_conf:
                command += ["-conf", config_path]
        else:
            for filename, file_settings in config_files.items():
                write_config(os.path.join(self.temp_dir, filename), file_settings)
            if explicit_conf:
                config_path = os.path.join(self.temp_dir, "ammServ.conf")
                if not os.path.exists(config_path):
                    write_config(config_path, settings)
                command += ["-conf", config_path]

        environment = dict(os.environ)
        environment["LD_LIBRARY_PATH"] = (
            LIBRARY_DIR
            + (":" + environment["LD_LIBRARY_PATH"] if environment.get("LD_LIBRARY_PATH") else "")
        )

        if not os.path.isfile(SERVER_BINARY):
            raise RuntimeError(
                "server binary not found: %s (build it first, or set AMMARSERVER_BINARY)" % SERVER_BINARY
            )

        self.process = subprocess.Popen(
            command,
            cwd=self.temp_dir,
            stdout=self.log_file,
            stderr=subprocess.STDOUT,
            env=environment,
        )
        self._wait_until_ready()

    def _create_fixtures(self):
        range_path = os.path.join(self.web_root, "range.bin")
        with open(range_path, "wb") as fixture:
            fixture.write(RANGE_BYTES)
        os.utime(range_path, (FIXED_MTIME, FIXED_MTIME))

        fixtures = {
            "empty.bin": b"",
            "index.html": b"<html><body>index fixture</body></html>",
            "text.txt": b"plain text fixture\n",
            "style.css": b"body { color: black; }\n",
            "image.png": PNG_BYTES,
            os.path.join("subdir", "child.txt"): b"directory listing child\n",
        }
        for relative_path, content in fixtures.items():
            path = os.path.join(self.web_root, relative_path)
            with open(path, "wb") as fixture:
                fixture.write(content)

    def _wait_until_ready(self):
        deadline = time.time() + 10.0
        while time.time() < deadline:
            if self.process.poll() is not None:
                raise RuntimeError("server exited during startup:\n%s" % self.log_tail())
            try:
                connection = socket.create_connection(("127.0.0.1", self.port), timeout=0.25)
                connection.close()
                return
            except OSError:
                time.sleep(0.05)
        raise RuntimeError("server did not start listening in time:\n%s" % self.log_tail())

    def log_tail(self, lines=60):
        try:
            with open(self.log_path, "rb") as log:
                data = log.read().decode("utf-8", "replace").splitlines()
            return "\n".join(data[-lines:])
        except OSError:
            return "<no log>"

    def _read_logs_with_prefix(self, prefix):
        contents = []
        if not os.path.isdir(self.log_dir):
            return b""
        for name in sorted(os.listdir(self.log_dir)):
            if name.startswith(prefix):
                try:
                    with open(os.path.join(self.log_dir, name), "rb") as log:
                        contents.append(log.read())
                except OSError:
                    pass
        return b"\n".join(contents)

    def read_access_logs(self):
        # Call this after stop(cleanup=False): the log files are fully buffered
        # and only flushed by the server's clean shutdown path.
        return self._read_logs_with_prefix("ammarserver_access.log")

    def read_error_logs(self):
        return self._read_logs_with_prefix("ammarserver_error.log")

    def stop(self, cleanup=True):
        if getattr(self, "process", None) is not None and self.process.poll() is None:
            self.process.terminate()
            try:
                self.process.wait(timeout=5)
            except subprocess.TimeoutExpired:
                self.process.kill()
                self.process.wait(timeout=5)
        if not self.log_file.closed:
            self.log_file.close()
        if cleanup:
            self.cleanup()

    def cleanup(self):
        shutil.rmtree(self.temp_dir, ignore_errors=True)


